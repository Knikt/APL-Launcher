"""Build app/assets/aerials/catalog.js from Apple's aerial index.

The footage is Apple's own tvOS aerial series. Nothing is downloaded or
redistributed: every entry is a URL on sylvan.apple.com that the set streams
directly, and the catalogue holds only names, captions and addresses.

The index used here is the public mirror at bzamayo.com, which lists Apple's
whole gallery with its on-screen captions and the 1080p H.264 rendition
(`_2K_AVC.mov`). Apple's own `Aerials/*/entries.json` now offers HEVC only, and
that container is not safe to hand a television's web engine.

Run: python scripts/build-aerial-catalog.py [--check]
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path

SOURCE = 'https://bzamayo.com/extras/apple-tv-screensavers.json'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'app/assets/aerials/catalog.js'

# The gallery's own headings, kept as the four themes the settings screen
# offers. A title belongs to the theme its footage was shot for, not to the
# first clip that names it.
THEMES = {
    'space': [
        'Africa Night', 'Africa and the Middle East', 'Antarctica',
        'Atlantic Ocean to Spain and France', 'Australia', 'California to Vegas',
        'Caribbean', 'Caribbean Day', 'Iran and Afghanistan', 'Ireland to Asia',
        'Italy to Asia', 'Korea and Japan Night', 'New York Night', 'New Zealand',
        'Nile Delta', 'North America Aurora', 'Sahara and Italy',
        'South Africa to North Asia', 'Southern California to Baja',
        'West Africa to the Alps',
    ],
    'city': ['Dubai', 'Hong Kong', 'London', 'Los Angeles', 'New York', 'San Francisco'],
    'underwater': [
        'Alaskan Jellies', 'Barracuda', 'Bumpheads', 'California Dolphins',
        'California Kelp Forest', 'Costa Rica Dolphins', 'Cownose Rays',
        'Gray Reef Sharks', 'Humpback Whale', 'Jacks', 'Kelp', 'Palau Coral',
        'Palau Jellies', 'Red Sea Coral', 'Sea Stars', 'Seals', 'Tahiti Waves',
    ],
}
ORDER = ['landscape', 'space', 'underwater', 'city']


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'CleanFrame/1.0'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode('utf-8'))


def caption_of(timed):
    """The first caption the gallery shows for a clip, which is its location."""
    if not timed:
        return ''
    first = min(timed, key=lambda k: int(k))
    return ' '.join(timed[first].replace('\u00a0', ' ').split())


def stream_url(url):
    """The same file over plain HTTP.

    sylvan.apple.com serves a chain that stops at "Apple Server Authentication
    CA" without the CA that issued it and without a caIssuers pointer, so no
    browser and no television can verify it: the request dies as an untrusted
    certificate and the clip never starts. The identical bytes are served over
    HTTP, which is what the set streams.
    """
    return url.replace('https://sylvan.apple.com/', 'http://sylvan.apple.com/', 1)


def theme_of(name):
    for theme, names in THEMES.items():
        if name in names:
            return theme
    return 'landscape'


def build(data):
    themes = {theme: [] for theme in ORDER}
    seen = {}
    for group in data:
        name = group['name']
        for clip in group.get('screensavers', []):
            url = clip.get('videoURL', '')
            if not url.endswith('.mov') or '_2K_AVC.mov' not in url:
                continue
            # A title can hold several clips; number them so the settings list
            # has no two identical rows.
            seen[name] = seen.get(name, 0) + 1
            label = name if seen[name] == 1 else name + ' ' + str(seen[name])
            themes[theme_of(name)].append({
                'name': label,
                'caption': caption_of(clip.get('timedCaptions')),
                'url': stream_url(url),
            })
    for rows in themes.values():
        rows.sort(key=lambda row: (row['name'].rstrip(' 0123456789'), row['name']))
    return themes


def render(themes):
    def quote(value):
        return json.dumps(value, ensure_ascii=False)

    lines = [
        '/* Apple TV aerial footage, streamed from Apple\'s own servers.',
        '',
        '   Generated by scripts/build-aerial-catalog.py. The videos are not',
        '   bundled and are not redistributed here: each entry is a URL on',
        '   sylvan.apple.com that the set loads directly, the same way the Apple',
        '   TV fetches them. `caption` is the place Apple prints over the same',
        '   clip. The addresses are plain HTTP on purpose: Apple serves that',
        '   host with a chain missing its issuing CA and with no caIssuers',
        '   pointer, so a browser or a set cannot verify it and the clip never',
        '   starts. A build with no route to those servers keeps its painted',
        '   scenes instead. */',
        'window.CleanFrameAerials = {',
    ]
    for index, theme in enumerate(ORDER):
        rows = themes[theme]
        lines.append(' %s: [' % quote(theme))
        for position, row in enumerate(rows):
            tail = ',' if position < len(rows) - 1 else ''
            lines.append('  {')
            lines.append('   "name": %s,' % quote(row['name']))
            lines.append('   "caption": %s,' % quote(row['caption']))
            lines.append('   "url": %s' % quote(row['url']))
            lines.append('  }' + tail)
        lines.append(' ]' + (',' if index < len(ORDER) - 1 else ''))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true',
                        help='fail instead of writing when the file is stale')
    args = parser.parse_args()
    themes = build(fetch(SOURCE)['data'])
    text = render(themes)
    total = sum(len(rows) for rows in themes.values())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('catalog.js is out of date; run python scripts/build-aerial-catalog.py')
        print('Aerial catalogue is current: %d clips.' % total)
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('Wrote %d clips to %s' % (total, OUT.relative_to(ROOT)))
    for theme in ORDER:
        print('  %-11s %d' % (theme, len(themes[theme])))


if __name__ == '__main__':
    main()
